#!/usr/bin/env python3
"""
regen_indexes.py — build plan/generated/ from upward links, and roll status up.

Called by:  hook .claude/hooks/on_plan_edit.py
            .claude/commands/plan-phases.md
            .claude/commands/plan-story.md
            .claude/commands/build-endpoint.md
            .claude/commands/verify-story.md
            .claude/commands/change-request.md
            .claude/commands/new-requirement.md
            .claude/commands/status.md
Calls:      .claude/scripts/_plan.py

Stdlib only.

Plan files declare their PARENTS only — see .claude/skills/plan-file-format.md.
Every downward view (phase to stories, story to endpoints, requirement to
implementations) is derived here by scanning those upward declarations, so a
child list can never drift out of date.

Status rolls up the same way: endpoints own their status, stories and phases
derive theirs. Derived status is written back into the frontmatter of the
story and phase files.

Exit code 0 normally; 1 with --check when anything is stale.

Usage:
    python .claude/scripts/regen_indexes.py
    python .claude/scripts/regen_indexes.py --check     # fail if stale
    python .claude/scripts/regen_indexes.py --quiet
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _plan import (  # noqa: E402
    Plan,
    PlanFile,
    find_project_root,
    load_plan,
)

GENERATED_BANNER = (
    "<!-- GENERATED by .claude/scripts/regen_indexes.py — do not hand-edit. -->\n"
    "<!-- Plan files declare parents only; this view is derived from them. -->\n"
)

# Endpoint statuses that count as finished work.
DONE = "done"
BLOCKING = "needs-rebuild"
NOT_STARTED = {"planned"}


# --------------------------------------------------------------------------
# Status roll-up
# --------------------------------------------------------------------------

def story_status(endpoints: list[PlanFile]) -> str:
    """Derive a story's status from its endpoints."""
    if not endpoints:
        return "planned"
    statuses = [ep.get_str("status") for ep in endpoints]
    if any(s == BLOCKING for s in statuses):
        return "in-progress"
    if all(s == DONE for s in statuses):
        return "complete"
    if all(s in NOT_STARTED for s in statuses):
        return "planned"
    return "in-progress"


def phase_status(stories: list[str]) -> str:
    """Derive a phase's status from its stories' derived statuses."""
    if not stories:
        return "not-started"
    if all(s == "complete" for s in stories):
        return "complete"
    if all(s == "planned" for s in stories):
        return "not-started"
    return "in-progress"


def set_frontmatter_value(text: str, key: str, value: str) -> str:
    """Replace one frontmatter key's value, leaving everything else intact."""
    pattern = re.compile(rf"^({re.escape(key)}:\s*).*$", re.MULTILINE)
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        return text
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        return text

    head = "".join(lines[: end + 1])
    tail = "".join(lines[end + 1 :])
    new_head, count = pattern.subn(rf"\g<1>{value}", head)
    return new_head + tail if count else text


# --------------------------------------------------------------------------
# Index building
# --------------------------------------------------------------------------

def build_views(plan: Plan) -> dict[str, str]:
    """Return {filename: content} for everything in plan/generated/."""
    # story -> endpoints, in ID order
    by_story: dict[str, list[PlanFile]] = {sid: [] for sid in plan.stories}
    orphan_endpoints: list[PlanFile] = []
    for ep in sorted(plan.endpoints.values(), key=lambda e: e.id):
        sid = ep.get_str("story")
        if sid in by_story:
            by_story[sid].append(ep)
        else:
            orphan_endpoints.append(ep)

    # phase -> stories
    by_phase: dict[str, list[PlanFile]] = {pid: [] for pid in plan.phases}
    orphan_stories: list[PlanFile] = []
    for story in sorted(plan.stories.values(), key=lambda s: s.id):
        pid = story.get_str("phase")
        if pid in by_phase:
            by_phase[pid].append(story)
        else:
            orphan_stories.append(story)

    derived_story = {
        sid: story_status(eps) for sid, eps in by_story.items()
    }

    views: dict[str, str] = {}

    # --- phase -> stories ------------------------------------------------
    out = [GENERATED_BANNER, "\n# Phases to stories\n"]
    for pid in sorted(by_phase, key=_phase_sort):
        phase = plan.phases[pid]
        statuses = [derived_story.get(s.id, "planned") for s in by_phase[pid]]
        out.append(
            f"\n## {pid} — {phase.get_str('name')} "
            f"[{phase_status(statuses)}]\n\n"
        )
        if not by_phase[pid]:
            out.append("*No stories.*\n")
            continue
        out.append("| Story | Name | Status | Endpoints |\n")
        out.append("|---|---|---|---|\n")
        for story in by_phase[pid]:
            eps = by_story.get(story.id, [])
            done = sum(1 for e in eps if e.get_str("status") == DONE)
            out.append(
                f"| {story.id} | {story.get_str('name')} "
                f"| {derived_story.get(story.id, 'planned')} "
                f"| {done}/{len(eps)} |\n"
            )
    if orphan_stories:
        out.append("\n## Stories with no valid phase\n\n")
        for story in orphan_stories:
            out.append(f"- {story.id} (phase: `{story.get_str('phase')}`)\n")
    views["phases-to-stories.md"] = "".join(out)

    # --- story -> endpoints ----------------------------------------------
    out = [GENERATED_BANNER, "\n# Stories to endpoints\n"]
    for sid in sorted(by_story):
        story = plan.stories[sid]
        out.append(
            f"\n## {sid} — {story.get_str('name')} "
            f"[{derived_story[sid]}]\n\n"
        )
        eps = by_story[sid]
        if not eps:
            out.append("*No endpoints yet.*\n")
            continue
        out.append("| Endpoint | Method | Path | Status | Contract |\n")
        out.append("|---|---|---|---|---|\n")
        for ep in eps:
            out.append(
                f"| {ep.id} | {ep.get_str('method')} | `{ep.get_str('path')}` "
                f"| {ep.get_str('status')} | `{ep.get_str('contract')}` |\n"
            )
    if orphan_endpoints:
        out.append("\n## Endpoints with no valid story\n\n")
        for ep in orphan_endpoints:
            out.append(f"- {ep.id} (story: `{ep.get_str('story')}`)\n")
    views["stories-to-endpoints.md"] = "".join(out)

    # --- requirement -> implementations ----------------------------------
    req_stories: dict[str, list[str]] = {}
    req_endpoints: dict[str, list[str]] = {}
    for story in plan.stories.values():
        for req in story.get_list("requirements"):
            req_stories.setdefault(req, []).append(story.id)
    for ep in plan.endpoints.values():
        for req in ep.get_list("requirements"):
            req_endpoints.setdefault(req, []).append(ep.id)

    out = [
        GENERATED_BANNER,
        "\n# Requirements to implementations\n\n",
        "Reverse index for impact analysis. "
        "A requirement with no claim is a coverage gap.\n\n",
        "| Requirement | Status | Stories | Endpoints |\n",
        "|---|---|---|---|\n",
    ]
    all_reqs = sorted(set(plan.requirements) | set(req_stories) | set(req_endpoints))
    for req in all_reqs:
        status = plan.requirements.get(req, "**MISSING**")
        stories = ", ".join(sorted(set(req_stories.get(req, [])))) or "—"
        eps = ", ".join(sorted(set(req_endpoints.get(req, [])))) or "—"
        out.append(f"| {req} | {status} | {stories} | {eps} |\n")
    if not all_reqs:
        out.append("| *none* | | | |\n")
    views["requirements-to-implementations.md"] = "".join(out)

    # --- open questions by target ----------------------------------------
    out = [
        GENERATED_BANNER,
        "\n# Open questions by target\n\n",
        "A story or endpoint listed here is blocked until its question "
        "is resolved.\n\n",
    ]
    rows: list[tuple[str, str, str]] = []
    for story in plan.stories.values():
        for q in story.get_list("questions"):
            rows.append((q, plan.questions.get(q, "**MISSING**"), story.id))
    for ep in plan.endpoints.values():
        for q in ep.get_list("questions"):
            rows.append((q, plan.questions.get(q, "**MISSING**"), ep.id))
    if rows:
        out.append("| Question | Status | Blocks |\n|---|---|---|\n")
        for q, status, target in sorted(rows):
            out.append(f"| {q} | {status} | {target} |\n")
    else:
        out.append("*No questions attached to any story or endpoint.*\n")
    views["questions-by-target.md"] = "".join(out)

    # --- error codes by endpoint -----------------------------------------
    out = [GENERATED_BANNER, "\n# Error codes by endpoint\n\n"]
    err_rows: list[tuple[str, str, str]] = []
    for ep in sorted(plan.endpoints.values(), key=lambda e: e.id):
        for err in ep.get_list("errors"):
            err_rows.append((err, plan.errors.get(err, "**MISSING**"), ep.id))
    if err_rows:
        out.append("| Error | Status | Endpoint |\n|---|---|---|\n")
        for err, status, ep_id in sorted(err_rows):
            out.append(f"| {err} | {status} | {ep_id} |\n")
    else:
        out.append("*No error codes referenced by any endpoint.*\n")
    views["errors-by-endpoint.md"] = "".join(out)

    return views


def _phase_sort(pid: str) -> tuple[int, str]:
    match = re.match(r"PH-(\d+)$", pid)
    return (int(match.group(1)), pid) if match else (9999, pid)


# --------------------------------------------------------------------------
# Writing
# --------------------------------------------------------------------------

def rollup_statuses(plan: Plan, check_only: bool) -> list[str]:
    """Write derived status into story and phase frontmatter."""
    changed: list[str] = []

    by_story: dict[str, list[PlanFile]] = {sid: [] for sid in plan.stories}
    for ep in plan.endpoints.values():
        sid = ep.get_str("story")
        if sid in by_story:
            by_story[sid].append(ep)

    derived_story: dict[str, str] = {}
    for sid, story in plan.stories.items():
        want = story_status(by_story[sid])
        derived_story[sid] = want
        if story.get_str("status") != want:
            changed.append(f"{story.path.name}: status -> {want}")
            if not check_only:
                text = set_frontmatter_value(story.body, "status", want)
                story.path.write_text(text, encoding="utf-8")

    for pid, phase in plan.phases.items():
        statuses = [
            derived_story[s.id]
            for s in plan.stories.values()
            if s.get_str("phase") == pid
        ]
        want = phase_status(statuses)
        if phase.get_str("status") != want:
            changed.append(f"{phase.path.name}: status -> {want}")
            if not check_only:
                text = set_frontmatter_value(phase.body, "status", want)
                phase.path.write_text(text, encoding="utf-8")

    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report staleness and exit 1; write nothing",
    )
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    root = find_project_root()
    plan = load_plan(root)

    if plan.problems:
        print(f"WARNING — {len(plan.problems)} plan file(s) could not be read:")
        for problem in plan.problems:
            print(f"  {problem}")
        print("Indexes built from the rest. Run check_links.py.\n")

    generated = plan.plan_dir / "generated"
    generated.mkdir(parents=True, exist_ok=True)

    views = build_views(plan)
    stale: list[str] = []

    for name, content in views.items():
        target = generated / name
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current != content:
            stale.append(name)
            if not args.check:
                target.write_text(content, encoding="utf-8")

    # Remove views no longer produced, so a renamed index cannot linger.
    for path in sorted(generated.glob("*.md")):
        if path.name not in views:
            stale.append(f"{path.name} (obsolete)")
            if not args.check:
                path.unlink()

    status_changes = rollup_statuses(plan, args.check)

    if args.check:
        if stale or status_changes:
            print("STALE — regenerate with: python .claude/scripts/regen_indexes.py")
            for name in stale:
                print(f"  index   {name}")
            for change in status_changes:
                print(f"  status  {change}")
            return 1
        if not args.quiet:
            print("OK — generated views and derived statuses are current")
        return 0

    if not args.quiet:
        counts = (
            f"{len(plan.phases)} phases, {len(plan.stories)} stories, "
            f"{len(plan.endpoints)} endpoints"
        )
        print(f"Regenerated {len(views)} view(s) in plan/generated/ ({counts})")
        for change in status_changes:
            print(f"  {change}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
